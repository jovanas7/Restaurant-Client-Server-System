    private void pripremiFormu() {
        setLocationRelativeTo(null);
        setTitle("Forma za pretragu gostiju");
        popuniTipove();
        srediTabelu();
    }

    private void popuniTipove() {
        try {
            cmbTipGosta.removeAllItems();
            List<TipGosta> tipovi = Kontroler.getInstanca().vratiSveTipoveGosta();
            for (TipGosta tipGosta : tipovi) {
                cmbTipGosta.addItem(tipGosta);
            }
            cmbTipGosta.setSelectedIndex(-1);
        } catch (GasenjeProgramaIzuzetak ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Upozorenje", JOptionPane.WARNING_MESSAGE);
            System.exit(0);
        } catch (ServerskiIzuzetak ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Greska prilikom ucitavanja tipova gosta", JOptionPane.ERROR_MESSAGE);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Doslo je do neocekivane greske prilikom ucitavanja tipova gosta.", "Greska prilikom ucitavanja tipova gosta", JOptionPane.ERROR_MESSAGE);
        }
    }

    public void srediTabelu() {
        try {
            List<Gost> listaGostiju = Kontroler.getInstanca().vratiSveGoste();
            modelTabeleGost = new ModelTabeleGost();
            tblGosti.setModel(modelTabeleGost);

            modelTabeleGost.setListaGostiju(listaGostiju);
        } catch (GasenjeProgramaIzuzetak ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Upozorenje", JOptionPane.WARNING_MESSAGE);
            System.exit(0);
        } catch (ServerskiIzuzetak ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Greska prilikom ucitavanja gostiju", JOptionPane.ERROR_MESSAGE);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Doslo je do neocekivane greske prilikom ucitavanja gostiju.", "Greska prilikom ucitavanja gostiju", JOptionPane.ERROR_MESSAGE);
        }
    }
