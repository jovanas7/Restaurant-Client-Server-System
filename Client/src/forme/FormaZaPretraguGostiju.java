    private void btnDetaljiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDetaljiActionPerformed
        int izabraniRed = tblGosti.getSelectedRow();

        if (izabraniRed == -1) {
            JOptionPane.showMessageDialog(this, "Morate izabrati gosta iz tabele!", "Detalji o gostu", JOptionPane.WARNING_MESSAGE);
        } else {
            try {
                modelTabeleGost = (ModelTabeleGost) tblGosti.getModel();
                Gost izabraniGost = modelTabeleGost.vratiGosta(izabraniRed);
                
                Gost gost = Kontroler.getInstanca().vratiGosta(izabraniGost.getIdGost());
                JOptionPane.showMessageDialog(this, "Sistem je nasao gosta.", "Detalji o gostu", JOptionPane.INFORMATION_MESSAGE);
                
                FormaGost formaGostPrikaz = new FormaGost(this, true, StatusForme.PRIKAZI,gost);
                formaGostPrikaz.setVisible(true);
                
            } catch (GasenjeProgramaIzuzetak ex) {
                JOptionPane.showMessageDialog(this, ex.getMessage(), "Upozorenje", JOptionPane.WARNING_MESSAGE);
                System.exit(0);
            } catch (ServerskiIzuzetak ex) {
                JOptionPane.showMessageDialog(this, ex.getMessage(), "Greska prilikom ucitavanja gosta", JOptionPane.ERROR_MESSAGE);
            } catch (Exception ex) {
                JOptionPane.showMessageDialog(this, "Doslo je do neocekivane greske prilikom ucitavanja izabranog gosta.", "Greska prilikom ucitavanja gosta", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnDetaljiActionPerformed

