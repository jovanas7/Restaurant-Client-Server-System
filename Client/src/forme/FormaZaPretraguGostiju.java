    private void btnPretraziActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPretraziActionPerformed
        TipGosta tipGosta = (TipGosta) cmbTipGosta.getSelectedItem();
        String ime=txtImeGosta.getText().trim();
        if (tipGosta == null && txtImeGosta.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Morate popuniti tip i/ili ime gosta prilikom pretrage gostiju!", "Pretraga gostiju", JOptionPane.WARNING_MESSAGE);
        } else {
            List<Gost> listaGostiju;
            try {
                listaGostiju = Kontroler.getInstanca().pretraziGoste(tipGosta,ime);

                modelTabeleGost = new ModelTabeleGost();
                tblGosti.setModel(modelTabeleGost);

                if (listaGostiju.isEmpty()) {
                    JOptionPane.showMessageDialog(this, "Sistem ne moze da pronadje goste po zadatim kriterijumima.", "Greska prilikom pretrage gostiju", JOptionPane.ERROR_MESSAGE);
                    return;
                } else {
                    JOptionPane.showMessageDialog(this, "Sistem je nasao goste po zadatim kriterijumima.", "Pretraga gostiju", JOptionPane.INFORMATION_MESSAGE);
                }

                modelTabeleGost.setListaGostiju(listaGostiju);

            } catch (GasenjeProgramaIzuzetak ex) {
                JOptionPane.showMessageDialog(this, ex.getMessage(), "Upozorenje", JOptionPane.WARNING_MESSAGE);
                System.exit(0);
            } catch (ServerskiIzuzetak ex) {
                JOptionPane.showMessageDialog(this, ex.getMessage(), "Greska prilikom pretrage gostiju", JOptionPane.ERROR_MESSAGE);
            } catch (Exception ex) {
                JOptionPane.showMessageDialog(this, "Doslo je do neocekivane greske prilikom pretrage gostiju.", "Greska prilikom pretrage gostiju", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnPretraziActionPerformed

