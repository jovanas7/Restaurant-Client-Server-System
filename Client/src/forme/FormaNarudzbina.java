    private void pripremiFormu(StatusForme status) {
        setLocationRelativeTo(null);
        popuniGoste();
        srediTabeluArtikala();
        srediTabeluStavki();
        popuniKonobara();

        switch (status) {
            case DODAJ:
                btnDugme.setText("Sacuvaj narudzbinu");

                txtUkupanIznos.setEditable(false);
                cmbKonobar.setEnabled(false);

                txtIDNarudzbina.setVisible(false);
                lblIDNarudzbenica.setVisible(false);

                SimpleDateFormat sdf = new SimpleDateFormat("dd.MM.yyyy");
                txtDatumNarucivanja.setText(sdf.format(new Date()));

                setTitle("Forma za dodavanje narudzbine");
                break;
            case PRIKAZI:
                btnDugme.setText("Izmeni narudzbinu");
                txtIDNarudzbina.setEnabled(false);
                txtDatumNarucivanja.setEnabled(false);
                cmbNacinPlacanja.setEnabled(false);

                tblArtikli.setEnabled(false);
                btnDodajStavkuNarudzbine.setEnabled(false);
                tblStavkeNarudzbine.setEnabled(false);
                btnObrisiStavkuNarudzbine.setEnabled(false);

                txtUkupanIznos.setEnabled(false);
                txtNapomena.setEnabled(false);
                cmbKonobar.setEnabled(false);
                cmbGost.setEnabled(false);

                popuniPoljaZaIzabranuNarudzbinu(izabranaNarudzbina);
                break;
            case IZMENI:
                btnDugme.setText("Potvrdi izmene");
                txtUkupanIznos.setEnabled(false);
                txtIDNarudzbina.setEnabled(false);
                cmbKonobar.setEnabled(false);
                setTitle("Forma za izmenu narudzbine");
                popuniPoljaZaIzabranuNarudzbinu(izabranaNarudzbina);
                break;

        }
    }

    private void popuniGoste() {
        try {
            cmbGost.removeAllItems();
            List<Gost> sviGosti = Kontroler.getInstanca().vratiSveGoste();
            for (Gost gost : sviGosti) {
                cmbGost.addItem(gost);
            }
        } catch (GasenjeProgramaIzuzetak ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Upozorenje", JOptionPane.WARNING_MESSAGE);
            System.exit(0);
        } catch (ServerskiIzuzetak ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Greska prilikom ucitavanja liste gostiju", JOptionPane.ERROR_MESSAGE);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Doslo je do neocekivane greske prilikom ucitavanja liste gostiju.", "Greska", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void srediTabeluArtikala() {
        try {
            List<Artikal> listaArtikala = Kontroler.getInstanca().vratiSveArtikle();
            ModelTabeleArtikal modelTabeleArtikal = new ModelTabeleArtikal();
            tblArtikli.setModel(modelTabeleArtikal);
            modelTabeleArtikal.setListaArtikala(listaArtikala);

        } catch (GasenjeProgramaIzuzetak ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Upozorenje", JOptionPane.WARNING_MESSAGE);
            System.exit(0);
        } catch (ServerskiIzuzetak ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Greska prilikom ucitavanja liste artikala", JOptionPane.ERROR_MESSAGE);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Doslo je do neocekivane greske prilikom ucitavanja liste artikala.", "Greska", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void srediTabeluStavki() {
        ModelTabeleStavkaNarudzbine modelTabeleStavke = new ModelTabeleStavkaNarudzbine();
        tblStavkeNarudzbine.setModel(modelTabeleStavke);
        modelTabeleStavke.setTxtUkupanIznos(txtUkupanIznos);
    }

    private void popuniKonobara() {
        try {
            cmbKonobar.removeAllItems();
            List<Konobar> listaKonobara = Kontroler.getInstanca().vratiSveKonobare();
            for (Konobar k : listaKonobara) {
                cmbKonobar.addItem(k);
            }
            Konobar ulogovani = Sesija.getInstanca().getUlogovaniKonobar();
            cmbKonobar.setSelectedItem(ulogovani);

        } catch (GasenjeProgramaIzuzetak ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Upozorenje", JOptionPane.WARNING_MESSAGE);
            System.exit(0);
        } catch (ServerskiIzuzetak ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Greska prilikom ucitavanja liste konobara", JOptionPane.ERROR_MESSAGE);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Doslo je do neocekivane greske prilikom ucitavanja liste konobara.", "Greska", JOptionPane.ERROR_MESSAGE);
        }

    }

    private void popuniPoljaZaIzabranuNarudzbinu(Narudzbina narudzbina) {
        txtIDNarudzbina.setText(String.valueOf(narudzbina.getIdNarudzbina()));
        SimpleDateFormat sdf = new SimpleDateFormat("dd.MM.yyyy");
        txtDatumNarucivanja.setText(sdf.format(narudzbina.getDatumNarucivanja()));
        cmbGost.setSelectedItem(narudzbina.getGost());
        txtNapomena.setText(narudzbina.getNapomena());
        cmbKonobar.setSelectedItem(narudzbina.getKonobar());
        cmbNacinPlacanja.setSelectedItem(narudzbina.getNacinPlacanja());
        
        ModelTabeleStavkaNarudzbine modelTabeleStavke = new ModelTabeleStavkaNarudzbine();
        modelTabeleStavke.setTxtUkupanIznos(txtUkupanIznos);
        tblStavkeNarudzbine.setModel(modelTabeleStavke);
        modelTabeleStavke.dodajListuStavkiNarudzbina(narudzbina.getStavkeNarudzbine());

    }
