    private void btnDodajStavkuNarudzbineActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDodajStavkuNarudzbineActionPerformed
        int izabraniRed = tblArtikli.getSelectedRow();

        if (izabraniRed == -1) {
            JOptionPane.showMessageDialog(this, "Morate izabrati artikal iz tabele!", "Dodavanje narudzbine", JOptionPane.WARNING_MESSAGE);

        } else {
            ModelTabeleArtikal modelTabeleArtikal = (ModelTabeleArtikal) tblArtikli.getModel();
            Artikal izabraniArtikal = modelTabeleArtikal.vratiArtikal(izabraniRed);
            if (!izabraniArtikal.isDostupan()) {
                JOptionPane.showMessageDialog(null, "Artikal nije dostupan!", "Dodavanje narudzbine", JOptionPane.WARNING_MESSAGE);
                return;
            }
            ModelTabeleStavkaNarudzbine modelTabeleStavke = (ModelTabeleStavkaNarudzbine) tblStavkeNarudzbine.getModel();
            modelTabeleStavke.dodajStavku(izabraniArtikal);
        }
    }//GEN-LAST:event_btnDodajStavkuNarudzbineActionPerformed

    private void btnObrisiStavkuNarudzbineActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnObrisiStavkuNarudzbineActionPerformed
        int izabraniRed = tblStavkeNarudzbine.getSelectedRow();
        if (izabraniRed == -1) {
            JOptionPane.showMessageDialog(this, "Morate izabrati stavku narudzbine iz tabele!", "Dodavanje narudzbine", JOptionPane.WARNING_MESSAGE);
        } else {
            ModelTabeleStavkaNarudzbine modelTabeleStavka = (ModelTabeleStavkaNarudzbine) tblStavkeNarudzbine.getModel();
            modelTabeleStavka.obrisiStavku(izabraniRed);
        }
    }//GEN-LAST:event_btnObrisiStavkuNarudzbineActionPerformed

    private void btnDugmeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDugmeActionPerformed

        // PRIKAZ
        if (status.equals(StatusForme.PRIKAZI)) {
            this.dispose();
            FormaNarudzbina formaNarudzbinaIzmena = new FormaNarudzbina((FormaZaPretraguNarudzbina) this.getParent(), true, StatusForme.IZMENI, izabranaNarudzbina);
            formaNarudzbinaIzmena.setVisible(true);
            return;
        }
        //DODAVANJE
        if (status.equals(StatusForme.DODAJ)) {

            try {
                if (txtDatumNarucivanja.getText().isEmpty()) {
                    throw new Exception("Morate uneti datum naručivanja!");
                }

                SimpleDateFormat sdf = new SimpleDateFormat("dd.MM.yyyy");

                Date datumNarucivanja;
                try {
                    datumNarucivanja = sdf.parse(txtDatumNarucivanja.getText());
                } catch (ParseException ex) {
                    throw new Exception("Neispravan format datuma (dd.MM.yyyy)!");
                }

                Date danas = sdf.parse(sdf.format(new Date()));

                if (datumNarucivanja.after(danas)) {
                    throw new Exception("Datum naručivanja ne sme biti u buducnosti!");
                }

                ModelTabeleStavkaNarudzbine mts
                        = (ModelTabeleStavkaNarudzbine) tblStavkeNarudzbine.getModel();

                if (mts.getListaStavki().isEmpty()) {
                    throw new Exception("Narudžbina mora sadržati barem jednu stavku!");
                }

                Narudzbina narudzbina = new Narudzbina();

                narudzbina.setGost((Gost) cmbGost.getSelectedItem());
                narudzbina.setNacinPlacanja((NacinPlacanja) cmbNacinPlacanja.getSelectedItem());
                narudzbina.setNapomena(txtNapomena.getText());
                narudzbina.setStavkeNarudzbine(mts.getListaStavki());

                narudzbina.setUkupanIznos(new BigDecimal(txtUkupanIznos.getText()));

                narudzbina.setKonobar(Sesija.getInstanca().getUlogovaniKonobar());
                narudzbina.setDatumNarucivanja(datumNarucivanja);

                Kontroler.getInstanca().dodajNarudzbinu(narudzbina);

                JOptionPane.showMessageDialog(this,
                        "Sistem je zapamtio narudzbinu.",
                        "Dodavanje narudzbine",
                        JOptionPane.INFORMATION_MESSAGE);

                this.dispose();
            } catch (GasenjeProgramaIzuzetak ex) {
                JOptionPane.showMessageDialog(this, ex.getMessage(), "Upozorenje", JOptionPane.WARNING_MESSAGE);
                System.exit(0);
            } catch (ServerskiIzuzetak ex) {
                JOptionPane.showMessageDialog(this, ex.getMessage(), "Greska prilikom dodavanja narudzbine", JOptionPane.ERROR_MESSAGE);
            } catch (Exception ex) {
                JOptionPane.showMessageDialog(this, "Doslo je do neocekivane greske prilikom dodavanja narudzbine.", "Greska prilikom dodavanja narudzbine", JOptionPane.ERROR_MESSAGE);
            }

        }
        // IZMENA
        if (status.equals(StatusForme.IZMENI)) {

            try {
                Narudzbina narudzbina = izabranaNarudzbina;
                ModelTabeleStavkaNarudzbine mts
                        = (ModelTabeleStavkaNarudzbine) tblStavkeNarudzbine.getModel();

                if (mts.getListaStavki().isEmpty()) {
                    throw new Exception("Narudžbina mora imati barem jednu stavku!");
                }
                SimpleDateFormat sdf = new SimpleDateFormat("dd.MM.yyyy");

                Date datumNarucivanja;
                try {
                    datumNarucivanja = sdf.parse(txtDatumNarucivanja.getText());
                } catch (ParseException ex) {
                    throw new Exception("Neispravan format datuma (dd.MM.yyyy)!");
                }
                narudzbina.setDatumNarucivanja(datumNarucivanja);
                narudzbina.setKonobar((Konobar) cmbKonobar.getSelectedItem());
                narudzbina.setGost((Gost) cmbGost.getSelectedItem());
                narudzbina.setNacinPlacanja((NacinPlacanja) cmbNacinPlacanja.getSelectedItem());
                narudzbina.setNapomena(txtNapomena.getText());
                narudzbina.setStavkeNarudzbine(mts.getListaStavki());

                narudzbina.setUkupanIznos(new BigDecimal(txtUkupanIznos.getText()));

                Kontroler.getInstanca().izmeniNarudzbinu(narudzbina);

                if (getParent() instanceof FormaZaPretraguNarudzbina) {
                    ((FormaZaPretraguNarudzbina) getParent()).srediTabelu();
                }

                JOptionPane.showMessageDialog(this,"Sistem je zapamtio narudzbinu.","Izmena", JOptionPane.INFORMATION_MESSAGE);
                this.dispose();

            } catch (GasenjeProgramaIzuzetak ex) {
                JOptionPane.showMessageDialog(this, ex.getMessage(), "Upozorenje", JOptionPane.WARNING_MESSAGE);
                System.exit(0);
            } catch (ServerskiIzuzetak ex) {
                JOptionPane.showMessageDialog(this, ex.getMessage(), "Greska prilikom izmene narudzbine", JOptionPane.ERROR_MESSAGE);
            } catch (Exception ex) {
                JOptionPane.showMessageDialog(this, ex.getMessage(), "Greska prilikom izmene narudzbine", JOptionPane.ERROR_MESSAGE);
            }

        }
    }//GEN-LAST:event_btnDugmeActionPerformed

