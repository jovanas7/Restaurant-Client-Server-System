    private void btnOdjaviSeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnOdjaviSeActionPerformed
        Object[] moguciOdgovori = {"Da", "Ne"};
        int potvrdaOdjave = JOptionPane.showOptionDialog(this, "Da li sigurno zelite da se odjavite sa sistema?",
                "Potvrda odjave", JOptionPane.YES_NO_OPTION, JOptionPane.QUESTION_MESSAGE,
                null, moguciOdgovori, moguciOdgovori[0]);

        if (potvrdaOdjave == JOptionPane.YES_OPTION) {
            try {
                Kontroler.getInstanca().odjaviKonobara(Sesija.getInstanca().getUlogovaniKonobar());

                JOptionPane.showMessageDialog(this, "Uspesna odjava sa sistema.", "Odjava", JOptionPane.INFORMATION_MESSAGE);
                this.dispose();
                new FormaZaPrijavu().setVisible(true);
            } catch (GasenjeProgramaIzuzetak ex) {
                JOptionPane.showMessageDialog(this, ex.getMessage(), "Upozorenje", JOptionPane.WARNING_MESSAGE);
                System.exit(0);
            } catch (ServerskiIzuzetak ex) {
                JOptionPane.showMessageDialog(this, ex.getMessage(), "Greska prilikom odjave", JOptionPane.ERROR_MESSAGE);
            } catch (Exception ex) {
                JOptionPane.showMessageDialog(this, "Doslo je do neocekivane greske prilikom odjave sa sistema.", "Greska prilikom odjave", JOptionPane.ERROR_MESSAGE);
            }
        } else {
            return;
        }
    }//GEN-LAST:event_btnOdjaviSeActionPerformed

