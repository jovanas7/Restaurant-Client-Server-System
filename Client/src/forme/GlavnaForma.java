    private void miKreirajNovogGostaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_miKreirajNovogGostaActionPerformed

        try {
            List<TipGosta> tipovi=Kontroler.getInstanca().vratiSveTipoveGosta();
            Gost gost = new Gost();
            gost.setTipGosta(tipovi.get(0));
            gost = Kontroler.getInstanca().dodajGosta(gost);
            JOptionPane.showMessageDialog(this, "Sistem je kreirao gosta.", "Dodavanje gosta", JOptionPane.INFORMATION_MESSAGE);
            new FormaGost(null, true, StatusForme.DODAJ, gost).setVisible(true);

        } catch (GasenjeProgramaIzuzetak ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Upozorenje", JOptionPane.WARNING_MESSAGE);
            System.exit(0);
        } catch (ServerskiIzuzetak ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Greska prilikom dodavanja gosta", JOptionPane.ERROR_MESSAGE);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Doslo je do neocekivane greske prilikom dodavanja novog gosta.", "Greska prilikom dodavanja gosta", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_miKreirajNovogGostaActionPerformed

