    private void btnPokreniServerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPokreniServerActionPerformed
        try {
            if (Util.getInstanca().daLiJePrazanProperti()) {
                JOptionPane.showMessageDialog(this, "Property fajl je prazan. Morate uneti podatke za konfiguraciju!", "", JOptionPane.WARNING_MESSAGE);
                return;
            }
        } catch (Exception e) {
            System.out.println("Doslo je do greske prilikom pretrage properti fajla.");
            e.printStackTrace();
        }
        if (pokretanjeServera.isPokrenut() == false) {
            pokretanjeServera = new PokretanjeServera();
            pokretanjeServera.start();
            pokretanjeServera.setPokrenut(true);
            serverJePokrenut();
            mKonfiguracija.setEnabled(false);
        }
    }//GEN-LAST:event_btnPokreniServerActionPerformed

    private void btnUgasiServerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUgasiServerActionPerformed
        if (pokretanjeServera.isPokrenut() == true) {
            pokretanjeServera.setPokrenut(false);
            pokretanjeServera.prekiniKlijentskePrograme();

            serverJeUgasen();
            mKonfiguracija.setEnabled(true);
        }
    }//GEN-LAST:event_btnUgasiServerActionPerformed
    private void formWindowClosed(java.awt.event.WindowEvent evt) {
        if (pokretanjeServera.isPokrenut() == true) {
            pokretanjeServera.prekiniKlijentskePrograme();
        }

        // Kontroler.getInstanca().ocistiListuUlogovanihFarmaceuta();
    }

