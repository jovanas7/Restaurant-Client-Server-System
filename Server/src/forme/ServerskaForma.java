    private void pripremiFormu() {
        setLocationRelativeTo(null);
        setTitle("Serverski program");

        txtStatusServera.setText("Serverski program nije pokrenut.");
        txtStatusServera.setEditable(false);
        btnPokreniServer.setEnabled(true);
        btnUgasiServer.setEnabled(false);

        srediTabelu();
    }

    private void srediTabelu() {
        ModelTabeleKonobar mtk = new ModelTabeleKonobar();
        tblUlogovaniKonobari.setModel(mtk);
    }

    private void serverJePokrenut() {
        txtStatusServera.setText("Serverski program je pokrenut!");
        btnPokreniServer.setEnabled(false);
        btnUgasiServer.setEnabled(true);
    }

    private void serverJeUgasen() {
        txtStatusServera.setText("Serverski program je ugasen.");
        btnPokreniServer.setEnabled(true);
        btnUgasiServer.setEnabled(false);
        Kontroler.getInstanca().ocistiListuUlogovanihKonobara();
        srediTabelu();
    }

    public ModelTabeleKonobar vratiTabeluUlogovanihKonobara() {
        return (ModelTabeleKonobar) tblUlogovaniKonobari.getModel();
    }

